    private static func stageRows(
        spec: CaseSpec,
        session: ProjectSession,
        compositor: MetalFrameCompositor,
        times: [Double]
    ) -> [StageRow] {
        let crop = session.document.canvas.cropRect01
        let sourceSize = CGSize(
            width: max(16, Double(sourceWidth) * crop.width),
            height: max(16, Double(sourceHeight) * crop.height)
        )
        let canvas = CGRect(origin: .zero, size: spec.canvas)
        return times.map { t in
            let zoom = session.trajectorySolver.evaluate(atSourceMs: t).camera.scale
            let stage = MetalFrameCompositor.resolvedStageLayout(
                session: session,
                sourceTimeMs: t,
                canvasRect: canvas,
                screenSourceSize: sourceSize,
                zoomScale: zoom
            )
            let screen = topLeft(stage.screenRect, canvasHeight: spec.canvas.height)
            let camera = topLeft(stage.camera.rect, canvasHeight: spec.canvas.height)
            return StageRow(
                sourceMs: t,
                canvas: [Double(spec.canvas.width), Double(spec.canvas.height)],
                screenRect: .init(x: screen.minX, y: screen.minY, width: screen.width, height: screen.height),
                camera: .init(
                    rect: .init(x: camera.minX, y: camera.minY, width: camera.width, height: camera.height),
                    cornerRadius: stage.camera.cornerRadius,
                    opacity: stage.camera.opacity,
                    shadowOpacity: stage.camera.shadowOpacity,
                    borderOpacity: stage.camera.borderOpacity,
                    isCutout: stage.camera.isCutout
                )
            )
        }
    }

    private static func topLeft(_ rect: CGRect, canvasHeight: CGFloat) -> CGRect {
        CGRect(x: rect.minX, y: canvasHeight - rect.maxY, width: rect.width, height: rect.height)
    }

    private static func captionRows(session: ProjectSession, times: [Double]) -> [CaptionRow] {
        let config = session.document.captions
        return times.map { t in
