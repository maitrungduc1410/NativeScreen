    private static func makeCase(
        id: String,
        canvas: CGSize = CGSize(width: 1280, height: 720),
        autoZoom: Bool = false,
        clicks: [ClickEvent]? = nil,
        keys: [KeyStrokeEvent]? = nil,
        hasCamera: Bool = false,
        _ edit: (inout ProjectDocument) -> Void
    ) -> CaseSpec {
        var doc = baseDocument(id: id)
        let clickEvents = clicks ?? baseClicks()
        let keyEvents = keys ?? baseKeys()
        if autoZoom {
            var zooms = AutoZoomClusterGenerator.generateZooms(
                clicks: clickEvents,
                keys: keyEvents,
                durationMs: durationMs,
                defaultScale: 2.0
            )
            for i in zooms.indices {
                zooms[i].id = "zoom-\(i + 1)"
            }
            doc.timeline.zooms = zooms
        }
        edit(&doc)
        return CaseSpec(
            id: id,
            document: doc,
            clicks: clickEvents,
            keys: keyEvents,
            hasCamera: hasCamera,
            canvas: canvas,
            frameTimes: [400, 1400, 2600, 4200]
        )
    }

