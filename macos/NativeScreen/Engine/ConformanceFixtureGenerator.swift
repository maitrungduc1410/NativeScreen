    private static func wallpaperImage() -> CGImage {
        draw(width: 960, height: 540) { ctx in
            let colors = [
                CGColor(red: 0.05, green: 0.20, blue: 0.45, alpha: 1),
                CGColor(red: 0.45, green: 0.20, blue: 0.55, alpha: 1)
            ] as CFArray
            let space = CGColorSpaceCreateDeviceRGB()
            let gradient = CGGradient(colorsSpace: space, colors: colors, locations: [0, 1])!
            ctx.drawLinearGradient(
                gradient,
                start: .zero,
                end: CGPoint(x: 960, y: 540),
                options: []
            )
        }
    }

    private static func draw(width: Int, height: Int, _ body: (CGContext) -> Void) -> CGImage {
        let colorSpace = CGColorSpaceCreateDeviceRGB()
        let ctx = CGContext(
            data: nil, width: width, height: height,
            bitsPerComponent: 8, bytesPerRow: width * 4,
            space: colorSpace,
            bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue
        )!
        body(ctx)
        return ctx.makeImage()!
    }

    private static func cgImage(pixels: [UInt8], width: Int, height: Int) throws -> CGImage {
        let colorSpace = CGColorSpaceCreateDeviceRGB()
        let storage = pixels
        guard let provider = CGDataProvider(data: Data(storage) as CFData),
              let image = CGImage(
                width: width, height: height,
                bitsPerComponent: 8, bitsPerPixel: 32, bytesPerRow: width * 4,
                space: colorSpace,
                bitmapInfo: CGBitmapInfo(rawValue: CGImageAlphaInfo.premultipliedLast.rawValue),
                provider: provider, decode: nil, shouldInterpolate: false, intent: .defaultIntent
              ) else {
            throw failure("Could not build the identity lattice image")
        }
        _ = storage
        return image
    }

