/// Hidden `--generate-conformance` mode. Builds deterministic projects, runs the macOS engines, and writes the
/// fixtures Windows is checked against (`spec/08` §2). No personal recordings are used.
@MainActor
enum ConformanceFixtureGenerator {
    private static let createdAt = "2026-01-01T00:00:00Z"
    private static let sourceWidth = 1280
    private static let sourceHeight = 720
    private static let durationMs = 6000.0

    static func generateAll(to root: URL) throws {
        let fm = FileManager.default
        if fm.fileExists(atPath: root.path) {
            try fm.removeItem(at: root)
        }
        try fm.createDirectory(at: root, withIntermediateDirectories: true)

        try writeLooks(to: root.appendingPathComponent("looks", isDirectory: true))

        let screen = syntheticScreenImage()
        let webcam = syntheticWebcamImage()
        var caseIds: [String] = []
        for spec in allCases() {
            // One compositor per case: its background crossfade runs on wall-clock time and would leak between cases.
            guard let compositor = MetalFrameCompositor() else {
                throw failure("Metal is unavailable; frame fixtures and stage layout need a GPU.")
            }
            let caseDir = root.appendingPathComponent("cases/\(spec.id)", isDirectory: true)
            try writeCase(spec, to: caseDir, screen: screen, webcam: webcam, compositor: compositor)
            caseIds.append(spec.id)
            fputs("conformance: \(spec.id)\n", stderr)
        }

        let readme = """
        # Conformance fixtures

        Generated by `Native Screen --generate-conformance` from synthetic projects (fixed telemetry, generated images).
        Do not edit by hand. Regenerate after changing the macOS engines.

        ## Tolerances (`spec/08` §2.4)

        - Numbers: `|a - b| ≤ 1e-6` relative or `≤ 1e-4` absolute. Discrete values (enums, ids, strings) exact.
        - Frames without text: SSIM ≥ 0.985 and max per-channel difference ≤ 6/255 on 99.5% of pixels.
        - Frames with text: SSIM ≥ 0.95. Text regions are excluded from the max-difference check.
        - Camera-look LUTs: max difference ≤ 2/255.

        ## Notes

        - Rects in `stage.json` are top-left origin, pixels. The macOS compositor works bottom-left; the generator converts.
        - `autozoom.json` ids are rewritten to `zoom-1`, `zoom-2`, ... in start-time order. Compare every other field as produced by `AutoZoomClusterGenerator`.
        - `estimates.json` stores the formatted size and duration strings plus the MP4 video bitrate in bits/second.
        - Default canvas is 1280×720. Aspect-ratio cases use a canvas with a 720 px short side (9:16 is 720×1280).
        - `shortcuts.json` includes `typingSuggestions` from the same keystrokes.

        Cases: \(caseIds.joined(separator: ", "))
        """
        try readme.write(to: root.appendingPathComponent("README.md"), atomically: true, encoding: .utf8)
    }

