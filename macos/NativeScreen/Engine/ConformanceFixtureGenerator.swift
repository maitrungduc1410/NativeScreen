            return CaptionRow(sourceMs: t, words: words)
        }
    }

    private static func shortcutRows(session: ProjectSession) -> ShortcutFile {
        let clusters = session.detectedShortcutClusters.map { cluster in
            ShortcutFile.Cluster(
                id: cluster.id,
                label: cluster.compactTimelineLabel,
                modifiers: cluster.modifiers,
                primaryKey: cluster.primaryKey,
                displayStartMs: cluster.displayStartMs,
                displayEndMs: cluster.displayEndMs,
                keyCaps: cluster.keyCaps.map {
                    ShortcutFile.Cap(key: $0.key, label: $0.label, symbol: $0.symbol, widthRatio: $0.widthRatio)
                }
            )
        }
        var envelopes: [ShortcutFile.Envelope] = []
        for cluster in session.detectedShortcutClusters {
            let marks = [
                cluster.displayStartMs,
                cluster.displayStartMs + 75,
                cluster.displayStartMs + 150,
                (cluster.displayStartMs + cluster.displayEndMs) * 0.5,
                cluster.displayEndMs - 90,
                cluster.displayEndMs
            ]
            for t in marks {
                let env = MetalFrameCompositor.shortcutTransitionEnvelope(for: cluster, atSourceMs: t)
                envelopes.append(ShortcutFile.Envelope(
                    clusterId: cluster.id,
                    sourceMs: t,
                    opacity: env.opacity,
                    scale: Double(env.scale),
                    slide: Double(env.slideOffsetMultiplier)
                ))
            }
        }
        let typing = session.activeTypingSuggestions.map {
            ShortcutFile.Typing(startKeyMs: $0.startKeyMs, sourceStartMs: $0.sourceStartMs, sourceEndMs: $0.sourceEndMs)
        }
        return ShortcutFile(clusters: clusters, envelopes: envelopes, typingSuggestions: typing)
    }

    private static func estimateRows(document: ProjectDocument) -> [EstimateRow] {
        let aspect = document.canvas.effectiveAspectRatio(sourceWidth: Double(sourceWidth), sourceHeight: Double(sourceHeight))
        var rows: [EstimateRow] = []
        for format in HardwareVideoExporter.ExportFormat.allCases {
            for fps in format.allowedFPSModes {
                for height in format.allResolutionHeights {
                    var config = HardwareVideoExporter.ExportConfiguration()
                    config.format = format
                    config.fps = fps
                    config.resolutionHeight = height
                    config.normalizeForConstraints()
                    switch format {
                    case .mp4:
                        for compression in HardwareVideoExporter.ExportCompression.allCases {
                            var c = config
                            c.compression = compression
                            c.mp4Codec = .h264
                            c.normalizeForConstraints()
                            guard c.resolutionHeight == height, c.fps == fps else { continue }
                            let bitrate = HardwareVideoExporter.targetMP4VideoBitrate(
                                compression: compression, codec: .h264,
                                widthPx: c.outputPixelSize(canvasAspect: aspect).width,
                                heightPx: c.outputPixelSize(canvasAspect: aspect).height,
                                fps: fps
                            )
                            rows.append(EstimateRow(
                                format: format.rawValue, fps: fps, height: height,
                                compression: compression.rawValue, codec: "h264",
                                size: HardwareVideoExporter.estimateOutputSizeString(config: c, canvasAspect: aspect, durationMs: durationMs, hasAudio: false),
                                duration: HardwareVideoExporter.estimateExportDurationString(config: c, canvasAspect: aspect, durationMs: durationMs),
                                videoBitrate: bitrate
                            ))
                        }
                    case .gif, .prores:
                        let size = HardwareVideoExporter.estimateOutputSizeString(config: config, canvasAspect: aspect, durationMs: durationMs, hasAudio: false)
                        let duration = HardwareVideoExporter.estimateExportDurationString(config: config, canvasAspect: aspect, durationMs: durationMs)
                        rows.append(EstimateRow(
                            format: format.rawValue, fps: fps, height: height,
                            compression: format == .gif ? (config.gifHighQuality ? "high" : "standard") : config.proResProfile.rawValue,
                            codec: format.rawValue,
                            size: size, duration: duration, videoBitrate: 0
                        ))
                    }
                }
            }
        }
        return rows
    }

    // MARK: - Looks

    private static func writeLooks(to dir: URL) throws {
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        let size = 33
        let width = size
        let height = size * size
        var pixels = [UInt8](repeating: 0, count: width * height * 4)
        for b in 0..<size {
            for g in 0..<size {
                for r in 0..<size {
                    let y = g + b * size
                    let i = (y * width + r) * 4
                    pixels[i] = UInt8((r * 255) / (size - 1))
                    pixels[i + 1] = UInt8((g * 255) / (size - 1))
                    pixels[i + 2] = UInt8((b * 255) / (size - 1))
                    pixels[i + 3] = 255
                }
            }
        }
        let identity = try cgImage(pixels: pixels, width: width, height: height)
        let context = CIContext(options: [.workingColorSpace: CGColorSpace(name: CGColorSpace.sRGB)!])
        for preset in CameraColorGradePreset.allCases where preset != .original {
            let graded = LocalOnDeviceMediaIntelligence.applyBuiltInLook(to: CIImage(cgImage: identity), preset: preset)
            guard let out = context.createCGImage(graded, from: CGRect(x: 0, y: 0, width: width, height: height)),
                  let data = out.dataProvider?.data,
                  let ptr = CFDataGetBytePtr(data) else {
                throw failure("Could not render look \(preset.rawValue)")
            }
            let bytesPerRow = out.bytesPerRow
            var lines = ["TITLE \"\(preset.rawValue)\"", "LUT_3D_SIZE \(size)", ""]
            for b in 0..<size {
                for g in 0..<size {
                    for r in 0..<size {
                        let yTop = g + b * size
                        let y = height - 1 - yTop
                        let i = y * bytesPerRow + r * 4
                        let rr = Double(ptr[i]) / 255.0
                        let gg = Double(ptr[i + 1]) / 255.0
                        let bb = Double(ptr[i + 2]) / 255.0
                        lines.append(String(format: "%.6f %.6f %.6f", rr, gg, bb))
                    }
                }
            }
            let name = preset.rawValue.lowercased()
            try lines.joined(separator: "\n").appending("\n").write(
                to: dir.appendingPathComponent("\(name).cube"),
                atomically: true,
                encoding: .utf8
            )
        }
    }

