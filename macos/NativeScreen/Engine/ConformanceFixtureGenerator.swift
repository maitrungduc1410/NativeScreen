    private static func sampleTimes(durationMs: Double, stepMs: Double) -> [Double] {
        var times: [Double] = []
        var t = 0.0
        while t <= durationMs + 0.001 {
            times.append(min(durationMs, t))
            t += stepMs
        }
        return times
    }

    private static func timeMapRows(session: ProjectSession, times: [Double]) -> [TimeMapRow] {
        let mapper = session.timeMapper
        let timelineStep = max(1.0, mapper.totalTimelineDurationMs / 30.0)
        var rows: [TimeMapRow] = []
        var t = 0.0
        while t <= mapper.totalTimelineDurationMs + 0.001 {
            let clamped = min(mapper.totalTimelineDurationMs, t)
            let mapped = mapper.sourceTime(forTimelineMs: clamped)
            let index = mapper.mappedSlices.firstIndex { clamped >= $0.timelineStartMs && clamped <= $0.timelineEndMs } ?? -1
            rows.append(TimeMapRow(timelineMs: clamped, sourceMs: mapped.sourceMs, sliceIndex: index))
            t += timelineStep
        }
        _ = times
        return rows
    }

