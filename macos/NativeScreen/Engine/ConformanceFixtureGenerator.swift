    private static func cursorPath(at tMs: Double) -> (x: Double, y: Double, kind: String) {
        let s = tMs / 1000.0
        let x = 0.18 + 0.64 * (0.5 + 0.5 * sin(s * 1.3))
        let y = 0.22 + 0.56 * (0.5 + 0.5 * cos(s * 0.85))
        let kind: String
        if tMs >= 2100 && tMs < 3400 {
            kind = "iBeam"
        } else if tMs >= 3400 && tMs < 4300 {
            kind = "pointingHand"
        } else if tMs >= 4300 && tMs < 4700 {
            kind = "crosshair"
        } else {
            kind = "arrow"
        }
        return (min(0.98, max(0.02, x)), min(0.98, max(0.02, y)), kind)
    }

    private static func baseCursorEvents() -> [CursorSampleEvent] {
        let step = 1000.0 / 120.0
        let count = Int(ceil(durationMs / step)) + 1
        return (0..<count).map { i in
            let t = min(durationMs, Double(i) * step)
            let p = cursorPath(at: t)
            return CursorSampleEvent(t: t, x: p.x, y: p.y, c: p.kind)
        }
    }

    private static func baseClicks() -> [ClickEvent] {
        let taps: [(Double, Double)] = [(450, 530), (720, 1180), (4000, 4090)]
        var events: [ClickEvent] = []
        for (down, up) in taps {
            let p = cursorPath(at: down)
            events.append(ClickEvent(t: down, type: "down", button: "left", x: p.x, y: p.y, count: 1))
            let q = cursorPath(at: up)
            events.append(ClickEvent(t: up, type: "up", button: "left", x: q.x, y: q.y, count: 1))
        }
        return events
    }

    private static func baseKeys() -> [KeyStrokeEvent] {
        var keys: [KeyStrokeEvent] = [
            KeyStrokeEvent(t: 2500, kind: "shortcut", modifiers: ["cmd", "shift"], key: "P", label: "⌘⇧P"),
            KeyStrokeEvent(t: 2680, kind: "shortcut", modifiers: ["cmd", "shift"], key: "P", label: "⌘⇧P")
        ]
        for i in 0..<24 {
            keys.append(KeyStrokeEvent(t: 3000 + Double(i) * 70, kind: "typing"))
        }
        return keys
    }

    private static func captionWords() -> [CaptionSegment] {
        let words = ["Native", "Screen", "renders", "the", "same", "frame", "on", "every", "platform", "today"]
        return words.enumerated().map { i, word in
            let start = 600.0 + Double(i) * 420.0
            return CaptionSegment(id: "word-\(i + 1)", sourceStartMs: start, sourceEndMs: start + 360, text: word)
        }
    }

    // MARK: - Write one case

    private static func writeCase(
        _ spec: CaseSpec,
        to caseDir: URL,
        screen: CGImage,
        webcam: CGImage,
        compositor: MetalFrameCompositor
    ) throws {
        let fm = FileManager.default
        let package = caseDir.appendingPathComponent("project.nativescreen", isDirectory: true)
        let recording = package.appendingPathComponent("recording", isDirectory: true)
        let telemetry = recording.appendingPathComponent("telemetry", isDirectory: true)
        let inputs = caseDir.appendingPathComponent("inputs", isDirectory: true)
        let expected = caseDir.appendingPathComponent("expected", isDirectory: true)
        try fm.createDirectory(at: telemetry, withIntermediateDirectories: true)
        try fm.createDirectory(at: inputs, withIntermediateDirectories: true)
        try fm.createDirectory(at: expected, withIntermediateDirectories: true)
        try fm.createDirectory(at: package.appendingPathComponent("assets", isDirectory: true), withIntermediateDirectories: true)

        try writePNG(screen, to: inputs.appendingPathComponent("screen.png"))
        if spec.hasCamera {
            try writePNG(webcam, to: inputs.appendingPathComponent("webcam.png"))
        }
        if spec.document.background.wallpaperRelativePath != nil {
            try writeJPEG(wallpaperImage(), to: package.appendingPathComponent("assets/background.jpg"))
        }

        let cursor = baseCursorEvents()
        try writeJSONL(cursor, to: telemetry.appendingPathComponent("cursor.jsonl"))
        try writeJSONL(spec.clicks, to: telemetry.appendingPathComponent("clicks.jsonl"))
        try writeJSONL(spec.keys, to: telemetry.appendingPathComponent("keys.jsonl"))
        try writeJSONL([WindowSample](), to: telemetry.appendingPathComponent("window.jsonl"))

        let metadata = RecordingMetadata(
            appVersion: "1.0.0",
            platform: "macos",
            createdAt: createdAt,
            durationMs: durationMs,
            captureTarget: CaptureTargetMetadata(
                mode: .display,
                displayId: 1,
                logicalBounds: LogicalBounds(x: 0, y: 0, width: 1280, height: 720),
                pixelSize: PixelDimensions(width: sourceWidth, height: sourceHeight),
                scaleFactor: 2,
                refreshRate: 60,
                windowBorderRadius: 0
            ),
            tracks: RecordingTracksMetadata(
                displayVideo: "display.mp4",
                webcamVideo: spec.hasCamera ? "webcam.mp4" : nil,
                microphoneAudio: nil,
                systemAudio: nil,
                cursorTelemetry: "telemetry/cursor.jsonl",
                clicksTelemetry: "telemetry/clicks.jsonl",
                keysTelemetry: "telemetry/keys.jsonl",
                windowTelemetry: "telemetry/window.jsonl"
            )
        )
        try writeJSON(metadata, to: recording.appendingPathComponent("metadata.json"))
        try writeJSON(spec.document, to: package.appendingPathComponent("project.json"))

        let session = try ProjectSession.load(from: package)
        var stored = session.document
        stored.createdAt = createdAt
        stored.updatedAt = createdAt
        try writeJSON(stored, to: package.appendingPathComponent("project.json"))

        let times = sampleTimes(durationMs: durationMs, stepMs: 200)
        try writeJSON(timeMapRows(session: session, times: times), to: expected.appendingPathComponent("timemap.json"))
        try writeJSON(trajectoryRows(session: session, times: times), to: expected.appendingPathComponent("trajectory.json"))
        try writeJSON(autoZoomRows(clicks: spec.clicks, keys: spec.keys), to: expected.appendingPathComponent("autozoom.json"))
        try writeJSON(
            stageRows(spec: spec, session: session, compositor: compositor, times: times),
            to: expected.appendingPathComponent("stage.json")
        )
        try writeJSON(captionRows(session: session, times: times), to: expected.appendingPathComponent("captions.json"))
        try writeJSON(shortcutRows(session: session), to: expected.appendingPathComponent("shortcuts.json"))
        try writeJSON(estimateRows(document: stored), to: expected.appendingPathComponent("estimates.json"))

        let framesDir = expected.appendingPathComponent("frames", isDirectory: true)
        try fm.createDirectory(at: framesDir, withIntermediateDirectories: true)
        let screenCI = CIImage(cgImage: screen)
        let webcamCI = spec.hasCamera ? CIImage(cgImage: webcam) : nil
        for t in spec.frameTimes where t <= durationMs {
            let frame = compositor.composeFrame(
                sourceVideoFrame: screenCI,
                sourceTimeMs: t,
                session: session,
                outputSize: spec.canvas,
                includeShortcutOverlay: true,
                webcamVideoFrame: webcamCI,
                isRealtimePreview: false
            )
            let extent = CGRect(origin: .zero, size: spec.canvas)
            guard let cg = compositor.ciContext.createCGImage(frame, from: extent) else {
                throw failure("Could not rasterize frame \(t) of \(spec.id)")
            }
            try writePNG(cg, to: framesDir.appendingPathComponent("\(Int(t)).png"))
        }
    }

