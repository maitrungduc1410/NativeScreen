public struct SystemWallpaperItem: Identifiable, Equatable, Sendable {
    public let id: String
    public let name: String
    public let fullImageURL: URL
    public let thumbnailURL: URL
    /// Bundled wallpapers are copied into the project byte for byte, so macOS and Windows store the same file.
    public var isBundled: Bool = false
}

/// Self-drawn wallpapers in `Wallpapers.bundle/<Category>/`, generated by `tools/generate_wallpapers.py`.
public enum BundledWallpaperCatalog {
    public static let categories = ["Spring", "Sunset", "Radiant", "Energy", "Iridescent", "Midnight", "Glassmorphism"]

    private static let itemsByCategory: [String: [SystemWallpaperItem]] = {
        guard let root = Bundle.main.url(forResource: "Wallpapers", withExtension: "bundle") else { return [:] }
        let fm = FileManager.default
        let thumbsDir = root.appendingPathComponent("thumbs", isDirectory: true)
        var result: [String: [SystemWallpaperItem]] = [:]
        for category in categories {
            let dir = root.appendingPathComponent(category, isDirectory: true)
            let files = (try? fm.contentsOfDirectory(at: dir, includingPropertiesForKeys: nil, options: [.skipsHiddenFiles])) ?? []
            result[category] = files
                .filter { $0.pathExtension.lowercased() == "jpg" }
                .sorted { $0.lastPathComponent < $1.lastPathComponent }
                .map { url in
                    let id = url.deletingPathExtension().lastPathComponent
                    return SystemWallpaperItem(
                        id: id,
                        name: id,
                        fullImageURL: url,
                        thumbnailURL: thumbsDir.appendingPathComponent(url.lastPathComponent),
                        isBundled: true
                    )
                }
        }
        return result
    }()

    public static func items(in category: String) -> [SystemWallpaperItem] {
        itemsByCategory[category] ?? []
    }

    public static var allItems: [SystemWallpaperItem] {
        categories.flatMap { items(in: $0) }
    }

    public static func category(ofWallpaperNamed name: String?) -> String? {
        guard let name else { return nil }
        return categories.first { category in items(in: category).contains { $0.name == name } }
    }
}

public enum SystemWallpaperCatalog {
    private static var cachedItems: [SystemWallpaperItem]?
    private static var thumbnailCache: [String: NSImage] = [:]
    private static let lock = NSLock()

    /// Discovers built-in macOS wallpapers from `/System/Library/Desktop Pictures/` once and caches the list.
    public static func discoverSystemWallpapers() -> [SystemWallpaperItem] {
        lock.lock()
        if let existing = cachedItems {
            lock.unlock()
            return existing
        }
        lock.unlock()

        var items: [SystemWallpaperItem] = []
        let fm = FileManager.default
        let desktopPicturesDir = URL(fileURLWithPath: "/System/Library/Desktop Pictures", isDirectory: true)
        let thumbnailsDir = desktopPicturesDir.appendingPathComponent(".thumbnails", isDirectory: true)

        if let mainScreen = NSScreen.main,
           let currentURL = NSWorkspace.shared.desktopImageURL(for: mainScreen),
           fm.fileExists(atPath: currentURL.path) {
            items.append(
                SystemWallpaperItem(
                    id: "current-desktop",
                    name: "Current Desktop",
                    fullImageURL: currentURL,
                    thumbnailURL: currentURL
                )
            )
        }

        let allowedExtensions: Set<String> = ["heic", "jpg", "jpeg", "png"]
        if let contents = try? fm.contentsOfDirectory(
            at: desktopPicturesDir,
            includingPropertiesForKeys: nil,
            options: [.skipsHiddenFiles]
        ) {
            for url in contents.sorted(by: { $0.lastPathComponent < $1.lastPathComponent }) {
                let ext = url.pathExtension.lowercased()
                guard allowedExtensions.contains(ext) else { continue }
                let baseName = url.deletingPathExtension().lastPathComponent
                let thumbCandidate = thumbnailsDir.appendingPathComponent("\(baseName).heic")
                let thumbJPGCandidate = thumbnailsDir.appendingPathComponent("\(baseName).jpg")
                let thumbURL: URL
                if fm.fileExists(atPath: thumbCandidate.path) {
                    thumbURL = thumbCandidate
                } else if fm.fileExists(atPath: thumbJPGCandidate.path) {
                    thumbURL = thumbJPGCandidate
                } else {
                    thumbURL = url
                }

                items.append(
                    SystemWallpaperItem(
                        id: baseName,
                        name: baseName,
                        fullImageURL: url,
                        thumbnailURL: thumbURL
                    )
                )
                if items.count >= 24 { break }
            }
        }

        lock.lock()
        cachedItems = items
        lock.unlock()
        return items
    }

    /// Preloads all system wallpaper thumbnails asynchronously on a background `.utility` queue so that SwiftUI
    /// on the `.userInteractive` MainActor thread NEVER blocks on synchronous `CGImageSourceCreateThumbnailAtIndex`
    /// (eliminating the ImageIO `.default` QoS priority inversion warning!).
    public static func preloadThumbnailsInBackground(for items: [SystemWallpaperItem], onComplete: (@Sendable @MainActor () -> Void)? = nil) {
        DispatchQueue.global(qos: .utility).async {
            var didLoadNew = false
            for item in items {
                lock.lock()
                let alreadyCached = (thumbnailCache[item.id] != nil)
                lock.unlock()
                if alreadyCached { continue }

                if let cgImg = downsampleCGImage(at: item.thumbnailURL, maxPixelSize: 200)
                    ?? downsampleCGImage(at: item.fullImageURL, maxPixelSize: 200) {
                    let nsImg = NSImage(cgImage: cgImg, size: NSSize(width: cgImg.width, height: cgImg.height))
                    lock.lock()
                    thumbnailCache[item.id] = nsImg
                    lock.unlock()
                    didLoadNew = true
                }
            }
            if didLoadNew, let onComplete {
                Task { @MainActor in
                    onComplete()
                }
            }
        }
    }

    /// Drops every cached thumbnail (called when the last editor closes; they are reloaded per category on demand).
    public static func purgeThumbnailCache() {
        lock.lock()
        thumbnailCache.removeAll()
        lock.unlock()
    }

    /// Returns a fast in-memory cached `NSImage` thumbnail (200px max dimension) without ever blocking the Main Thread.
    public static func cachedThumbnailImage(for item: SystemWallpaperItem) -> NSImage? {
        lock.lock()
        let hit = thumbnailCache[item.id]
        lock.unlock()
        return hit
    }

    /// Uses `ImageIO` thumbnailing to decode & downsample any `.heic`/`.jpg` into a `CGImage`.
    /// Note: `kCGImageSourceShouldCacheImmediately` is intentionally omitted when called from interactive threads
    /// because ImageIO's internal `.default`-QoS AppleJPEG worker pool triggers a priority inversion if waited on by `.userInteractive`.
    public static func downsampleCGImage(at url: URL, maxPixelSize: Int) -> CGImage? {
        let sourceOptions: [CFString: Any] = [
            kCGImageSourceShouldCache: false
        ]
        guard let source = CGImageSourceCreateWithURL(url as CFURL, sourceOptions as CFDictionary) else {
            return nil
        }
        let thumbOptions: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: maxPixelSize
        ]
        return CGImageSourceCreateThumbnailAtIndex(source, 0, thumbOptions as CFDictionary)
    }
}
